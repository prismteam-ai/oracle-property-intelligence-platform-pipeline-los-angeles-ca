/**
 * Synthetic run for the API tests (no binary file in the repo, no real parcel): a few rows with the
 * increment-1 Parquet columns, written at setup to a temporary directory together with a run manifest
 * and run history, under the file names the Lambda uses after its S3 copy.
 *
 * Rows around the reference point (34.199, -118.487), roll year 2026:
 *   0000000001 at the point, built 2010 (older than 15 years)      page-0000
 *   0000000002 ~0.5 mi north, built 1990                            page-0000
 *   0000000003 at the point, built 2011 (NOT older than 15 years)   page-0000
 *   0000000004 at the point, no year built (excluded)               page-0000
 *   0000000005 no coordinates, built 1950 (excluded)                page-0001
 *   0000000006 ~9 mi north, built 1950 (outside 5 mi, inside 10 mi)  page-0001
 *   0000000007 ~0.2 mi south, built 1940 (older than 80 years)      page-0001
 *
 * writeNearestFixture() writes a second run for the points cap: NEAREST.rows parcels generated by DuckDB
 * (range()): one at the point, built 1970, then pairs built 1950 on the same spot (equal distance), each
 * pair 1e-5 degree further north than the last (under 9 mi in all). Within a pair the row written first
 * has the higher parcel ID, so only an order by parcel ID (not file order) keeps the lower one.
 * - At 15 years all rows qualify (odd count): the 25,000th and 25,001st nearest are the two halves of one
 *   pair, so the cap cuts through a tie.
 * - At 60 years the 1970 parcel drops out (even count), so a radius between pairs 12,500 and 12,501 gives
 *   exactly 25,000.
 */
import { createHash } from "node:crypto";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { DuckDBInstance } from "@duckdb/node-api";

export const FIXTURE = {
  runId: "fixture-run",
  point: { lat: 34.199, lon: -118.487 },
  source: "Fixture Source",
  rows: 7,
  /** Not the pilot's "_slice" name: the file name is configuration (DataConfig.parquetFile). */
  parquetFile: "fixture_property_roll2026.parquet",
} as const;
/** The points-cap run (see the header). */
export const NEAREST = { rows: 25_003 } as const;
const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
/** One fixture row from SQL expressions for the ID, year built, coordinates and page file. */
const rowSql = (
  id: string,
  yb: string,
  lat: string,
  lon: string,
  page: string,
) => `select
  ${id} as parcel_identifier, ${id} as assessor_id_formatted, ${id} as request_identifier,
  ${yb}::integer as property_structure_built_year, ${yb}::integer as property_effective_built_year,
  'PROXY' as roof_age_basis, 'SFR' as source_use_type, '0100' as source_use_code, 'Single' as source_use_code_description,
  cast(${id}::bigint as varchar) || ' TEST ST' as unnormalized_address, cast(${id}::bigint as varchar) as street_number, null::varchar as street_pre_directional_text,
  'TEST ST' as street_name, null::varchar as unit_identifier, 'TEST CITY' as city_name, '00000' as postal_code, null::varchar as plus_four_postal_code,
  'Los Angeles' as county_name, 'CA' as state_code, ${lat}::double as latitude, ${lon}::double as longitude,
  'fixture' as coordinate_basis, 'LOS ANGELES' as tax_rate_area_city, '2026' as roll_year, date '2010-01-01' as last_recording_date,
  true as owner_unchanged_10y_proxy, null::boolean as out_of_area_owner,
  'https://example.test/query?page=' || ${page} as source_http_request, 'GET' as source_http_method,
  timestamptz '2026-11-11 16:17:40.932+00' as source_retrieved_at, 'sha-' || ${page} as source_page_sha256,
  ${page} as source_page_file, ${lit(FIXTURE.source)} as source_name`;
const row = (
  id: string,
  yb: number | null,
  lat: number | null,
  lon: number | null,
  page: string,
) =>
  rowSql(
    lit(id),
    String(yb ?? "null"),
    String(lat ?? "null"),
    String(lon ?? "null"),
    lit(page),
  );

/** Write the fixture files; returns the directory and the Parquet sha256. */
export async function writeFixture(): Promise<{
  dir: string;
  parquetSha256: string;
}> {
  const { lat, lon } = FIXTURE.point;
  return writeRun(
    [
      row("0000000001", 2010, lat, lon, "page-0000.json"),
      row("0000000002", 1990, lat + 0.00724, lon, "page-0000.json"),
      row("0000000003", 2011, lat, lon, "page-0000.json"),
      row("0000000004", null, lat, lon, "page-0000.json"),
      row("0000000005", 1950, null, null, "page-0001.json"),
      row("0000000006", 1950, lat + 0.13, lon, "page-0001.json"),
      row("0000000007", 1940, lat - 0.0029, lon, "page-0001.json"),
    ].join(" union all "),
  );
}

/**
 * The points-cap run. Row i (0-based) sits at step k = ceil(i / 2) north of the point; within a pair
 * (2k - 1, 2k) the first row gets the higher ID: id(2k - 1) = 2k + 1, id(2k) = 2k. Row 0 has ID 1.
 */
export async function writeNearestFixture(): Promise<{
  dir: string;
  parquetSha256: string;
}> {
  const { lat, lon } = FIXTURE.point;
  const id =
    "lpad(cast(case when i = 0 then 1 when i % 2 = 1 then i + 2 else i end as varchar), 10, '0')";
  return writeRun(
    `select * from (select range as i from range(${NEAREST.rows})) g, lateral (${rowSql(
      id,
      "case when i = 0 then 1970 else 1950 end",
      `${lat} + ceil(i / 2) * 0.00001`,
      String(lon),
      "'page-0000.json'",
    )})`,
  );
}

async function writeRun(
  selectSql: string,
): Promise<{ dir: string; parquetSha256: string }> {
  const dir = mkdtempSync(join(tmpdir(), "api-fixture-"));
  const parquet = join(dir, FIXTURE.parquetFile);
  const c = await (await DuckDBInstance.create(":memory:")).connect();
  await c.run(`copy (${selectSql}) to ${lit(parquet)} (format parquet)`);
  writeFileSync(
    join(dir, "run_manifest.json"),
    JSON.stringify({
      run_id: FIXTURE.runId,
      run_name: "fixture",
      generated_at: "2026-11-11T16:20:11.919Z",
      county: "Los Angeles",
      state: "CA",
      fips: "06037",
      roll_year: "2026",
      scope: { increment: 1 },
      readiness: { scope_guard: "PASS" },
      row_counts: { parquet: FIXTURE.rows },
      coverage: { with_coordinates: 6 },
      delta: { added: FIXTURE.rows, removed: 0 },
      limitations: ["fixture only"],
      derived_field_reference_date: "2026-11-11",
      sources: [
        {
          name: FIXTURE.source,
          role: "roll",
          hub_page: "https://example.test/hub",
          query_url: "https://example.test/query",
          terms_of_use: "https://example.test/terms",
          access: "anonymous",
        },
      ],
    }),
  );
  writeFileSync(
    join(dir, "run_history.jsonl"),
    JSON.stringify({
      run_id: FIXTURE.runId,
      finished_at: "2026-11-11T16:20:11.919Z",
      row_counts: { parquet: FIXTURE.rows },
      delta: { added: FIXTURE.rows, removed: 0 },
      parquet_sha256: "x",
      manifest_sha256: "y",
      published: false,
    }) + "\n",
  );
  return {
    dir,
    parquetSha256: createHash("sha256")
      .update(readFileSync(parquet))
      .digest("hex"),
  };
}
